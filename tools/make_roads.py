"""Road network of every mission map, for the mod's route walk (scanner.cpp, roads.cpp).

Usage: python -I make_roads.py <aotr folder> <out roads.txt>

A map's WaypointsList chunk (v1, read 2026-11-01) is u32 count, then count pairs of
(u32 from waypoint id, u32 to waypoint id); waypoint objects carry waypointID, waypointName
and waypointPathLabel1..3. The mission designers draw these paths for their own units
(marches, patrols, attacks, cutscene walks), so they run over ground those units can walk.
Paths for flying or swimming units are dropped by their labels. The mod joins nearby paths
itself (roads.cpp), because almost every path is a chain of its own.

Output, one section per map that has mission objectives (the mod finds the map by them):
    map <folder>
    tags <objective tag> ...
    n <x> <y>            (node index = order of n lines in the section, from 0)
    e <a> <b>            (a designer link between nodes a and b)
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mapfile  # noqa: E402

# Labels of paths that are not for walking: fliers (crebain, eagles, fell beasts, bats) and
# boats. Whole words: "ship" must not hit "Fellowship". A "Flee" path is the heroes running
# from the fliers on foot (Redhorn "Cinematic - Crebain - Flee Frodo"). Nazgul ride horses
# in the Fellowship missions (Weathertop "Fords - Nazgul 01 Path"), so they count as fliers
# only on the maps of the story where they ride fell beasts. The list follows the story,
# not the files: Weathertop's map names a fell beast too (the summoned spell
# "MordorFellBeast_Summoned"), so searching the map for "fell beast" does not tell.
AIR_OR_WATER = re.compile(r'crebain|eagles?\b|fell ?beasts?|\bbats?\b|\bfly|\bbirds?\b|\bboats?\b|\bships?\b', re.I)
NAZGUL = re.compile(r'nazgul', re.I)
ON_FOOT = re.compile(r'\bflee\b', re.I)
WINGED_NAZGUL_MAPS = {'map good osgiliath', 'map good taming of smeagol', 'map good lord of the rings',
                      'map good minas outer', 'map good minas inner', 'map good cirith ungol',
                      'map good pelennor fields', 'map good black gate'}


def air_or_water(labels, winged):
    if ON_FOOT.search(labels):
        return False
    return bool(AIR_OR_WATER.search(labels)) or (winged and bool(NAZGUL.search(labels)))


def main():
    aotr, out_path = sys.argv[1], sys.argv[2]
    maps = os.path.join(aotr, 'maps')
    out = open(out_path, 'w', encoding='utf-8', newline='\n')
    out.write('# Generated by tools\\make_roads.py from the maps\' waypoint paths. Do not edit by hand.\n')
    total_maps = total_nodes = total_links = 0
    for folder in sorted(os.listdir(maps)):
        mdir = os.path.join(maps, folder)
        ini, mpath = os.path.join(mdir, 'map.ini'), os.path.join(mdir, folder + '.map')
        if not (os.path.exists(ini) and os.path.exists(mpath)):
            continue
        text = open(ini, 'rb').read().decode('latin-1')
        tags = [t for _, t in re.findall(r'(Bonus)?MissionObjectiveTag\s*=\s*(\S+)', text)]
        if not tags:
            continue
        raw, pos, names = mapfile.load(mpath)
        winged = folder.lower() in WINGED_NAZGUL_MAPS
        links = []
        for name, ver, start, end, _ in mapfile.walk(raw, pos, names):
            if name == 'WaypointsList':
                n, = struct.unpack_from('<I', raw, start)
                if 4 + 8 * n != end - start:
                    print(f'{folder}: WaypointsList size {end - start} does not fit {n} links, skipped')
                    break
                links = [struct.unpack_from('<II', raw, start + 4 + 8 * i) for i in range(n)]
        if not links:
            continue
        wp = {}
        for tmpl, props, (x, y, z) in mapfile.objects(raw, pos, names):
            if 'waypointID' in props:
                labels = ' '.join(props.get(f'waypointPathLabel{i}', '') for i in (1, 2, 3))
                wp[props['waypointID']] = (x, y, labels)
        index = {}
        edges = []
        dropped = 0
        for a, b in links:
            if a not in wp or b not in wp or a == b:
                continue
            if air_or_water(wp[a][2], winged) or air_or_water(wp[b][2], winged):
                dropped += 1
                continue
            for w in (a, b):
                if w not in index:
                    index[w] = len(index)
            edges.append((index[a], index[b]))
        if not edges:
            continue
        out.write(f'\nmap {folder}\ntags {" ".join(tags)}\n')
        for w, i in sorted(index.items(), key=lambda kv: kv[1]):
            out.write(f'n {wp[w][0]:.0f} {wp[w][1]:.0f}\n')
        for a, b in edges:
            out.write(f'e {a} {b}\n')
        total_maps += 1
        total_nodes += len(index)
        total_links += len(edges)
        print(f'{folder}: {len(index)} nodes, {len(edges)} links, {dropped} air/water links dropped')
    print(f'{total_maps} maps, {total_nodes} nodes, {total_links} links -> {out_path}')


if __name__ == '__main__':
    main()
